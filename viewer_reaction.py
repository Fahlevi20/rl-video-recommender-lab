"""Generate one synthetic viewer response after a video is selected."""

import random
from dataclasses import dataclass

from candidate_generator import sample_catalog


@dataclass(frozen=True)
class Reaction:
    clicked: bool
    playback_seconds: int


def react_to_video(video, private_interest, rng):
    draw = rng.random()
    if video.topic == private_interest:
        ignore_end, short_end = 0.20, 0.40
    else:
        ignore_end, short_end = 0.50, 0.80

    if draw < ignore_end:
        return Reaction(False, 0)
    if draw < short_end:
        return Reaction(True, 5)
    return Reaction(True, 40)


def main():
    videos = {video.video_id: video for video in sample_catalog()}
    rng = random.Random(42)
    private_interest = "cooking"
    print("Synthetic reaction demo only: invented probabilities, not real viewer statistics.")
    print("Private simulator interest: cooking (not provided to the recommendation policy).")
    print("Matching video: 20% ignore, 20% play 5s, 60% play 40s.")
    print("Other video:    50% ignore, 30% play 5s, 20% play 40s.")

    for video_id in ("A", "C", "A", "C"):
        video = videos[video_id]
        print(f"\nSelected video {video.video_id} ({video.topic}) is shown.")
        response = react_to_video(video, private_interest, rng)
        if not response.clicked:
            print("Outcome: ignored (no click, 0s playback).")
        else:
            print(f"Outcome: clicked, played {response.playback_seconds}s; "
                  f"qualifying watch = {response.playback_seconds >= 30}.")
    print("\nNo later visit, event log, or RL reward is generated by this demo.")


if __name__ == "__main__":
    main()
